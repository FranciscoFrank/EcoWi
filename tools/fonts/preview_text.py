"""Writes res/drawable/preview_soc.xml: "78%" in Unbounded SemiBold as a VectorDrawable.

    pip install fonttools
    python tools/fonts/preview_text.py

Widget-picker previews (previewLayout) are inflated by the launcher, which doesn't load app fonts, and no
app code runs there. A vector made from the font's own glyph outlines is the only way to show the
percentage in the app's typeface. At runtime the widgets draw the text themselves (appwidget/SocText.kt).
"""
import os

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
FONT = os.path.join(ROOT, "app", "src", "main", "res", "font", "unbounded_semibold.ttf")
OUT = os.path.join(ROOT, "app", "src", "main", "res", "drawable", "preview_soc.xml")

TEXT = "78%"
SIZE_DP = 22  # same as SocText.ROW / SocText.RING


def main():
    font = TTFont(FONT)
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    upm = font["head"].unitsPerEm
    ascent, descent = font["hhea"].ascent, -font["hhea"].descent

    pen = SVGPathPen(glyphs, ntos=lambda v: ("%.1f" % v).rstrip("0").rstrip("."))
    x = 0
    for ch in TEXT:
        name = cmap[ord(ch)]
        # font units are y-up with the baseline at 0; the viewport is y-down with the ascent at the top
        glyphs[name].draw(TransformPen(pen, (1, 0, 0, -1, x, ascent)))
        x += glyphs[name].width
    width, height = x, ascent + descent

    xml = f'''<?xml version="1.0" encoding="utf-8"?>
<!-- "{TEXT}" in Unbounded SemiBold for widget-picker previews (generated by tools/fonts/preview_text.py).
     White mask: previews tint it with android:tint. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{width / upm * SIZE_DP:.2f}dp" android:height="{height / upm * SIZE_DP:.2f}dp"
    android:viewportWidth="{width}" android:viewportHeight="{height}">
    <path android:fillColor="#FFFFFFFF" android:pathData="{pen.getCommands()}" />
</vector>
'''
    open(OUT, "w").write(xml)
    print("wrote", os.path.relpath(OUT, ROOT), f"({width / upm * SIZE_DP:.1f} x {height / upm * SIZE_DP:.1f} dp)")


if __name__ == "__main__":
    main()
